import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const inputDir = path.join(root, "docs", "design-references");
const outputFile = path.join(root, "lib", "design", "imported-design-references.ts");

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/\.md$/i, "")
    .replace(/design|reference|style/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .trim();
}

function toTitle(value) {
  return value
    .replace(/\.md$/i, "")
    .replace(/[-_]+/g, " ")
    .replace(/\b\w/g, (char) => char.toUpperCase())
    .trim();
}

function inferTheme(content) {
  const lower = content.toLowerCase();

  if (
    lower.includes("theme: dark") ||
    lower.includes("dark theme") ||
    lower.includes("dark interface") ||
    lower.includes("dark, layered") ||
    lower.includes("near-black") ||
    lower.includes("midnight")
  ) {
    return "dark";
  }

  return "light";
}

function inferBestFor(id, content) {
  const lower = `${id} ${content}`.toLowerCase();
  const tags = new Set();

  if (lower.includes("linear")) {
    tags.add("polished-saas");
    tags.add("product-website");
    tags.add("ai-builder");
  }

  if (lower.includes("plain")) {
    tags.add("workbench");
    tags.add("dashboard");
    tags.add("admin");
    tags.add("support");
  }

  if (lower.includes("mercury")) {
    tags.add("fintech");
    tags.add("premium");
    tags.add("command-center");
  }

  if (lower.includes("warp")) {
    tags.add("developer-tool");
    tags.add("terminal");
    tags.add("infrastructure");
  }

  if (lower.includes("cycle")) {
    tags.add("soft-saas");
    tags.add("collaboration");
    tags.add("onboarding");
  }

  if (lower.includes("cyber") || lower.includes("security")) {
    tags.add("security");
    tags.add("enterprise");
  }

  if (tags.size === 0) {
    tags.add("saas");
    tags.add("website");
    tags.add("product-ui");
  }

  return Array.from(tags);
}

function excerpt(content, max = 900) {
  return content
    .replace(/\r\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .slice(0, max)
    .trim();
}

function escapeTs(value) {
  return JSON.stringify(value);
}

if (!fs.existsSync(inputDir)) {
  fs.mkdirSync(inputDir, { recursive: true });
}

const files = fs
  .readdirSync(inputDir)
  .filter((file) => file.toLowerCase().endsWith(".md"))
  .sort();

const references = files.map((file) => {
  const fullPath = path.join(inputDir, file);
  const content = fs.readFileSync(fullPath, "utf8");
  const id = slugify(file) || slugify(toTitle(file));

  return {
    id,
    name: toTitle(file),
    filename: file,
    theme: inferTheme(content),
    bestFor: inferBestFor(id, content),
    summary: excerpt(content),
    content,
  };
});

const output = `/* eslint-disable quotes */
/* eslint-disable max-len */
/**
 * This file is generated by scripts/build-design-references.mjs.
 * Do not edit this file manually.
 */

export type ImportedDesignReference = {
  id: string;
  name: string;
  filename: string;
  theme: "light" | "dark";
  bestFor: string[];
  summary: string;
  content: string;
};

export const IMPORTED_DESIGN_REFERENCES: ImportedDesignReference[] = [
${references
  .map(
    (reference) => `  {
    id: ${escapeTs(reference.id)},
    name: ${escapeTs(reference.name)},
    filename: ${escapeTs(reference.filename)},
    theme: ${escapeTs(reference.theme)},
    bestFor: ${escapeTs(reference.bestFor)},
    summary: ${escapeTs(reference.summary)},
    content: ${escapeTs(reference.content)},
  }`
  )
  .join(",\n")}
];

export function getImportedDesignReference(id?: string | null) {
  if (!id) return IMPORTED_DESIGN_REFERENCES[0] ?? null;

  return (
    IMPORTED_DESIGN_REFERENCES.find((reference) => reference.id === id) ??
    IMPORTED_DESIGN_REFERENCES[0] ??
    null
  );
}

export function inferImportedDesignReference(input: {
  prompt?: string | null;
  projectType?: string | null;
  industry?: string | null;
}) {
  const haystack = [input.prompt, input.projectType, input.industry]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();

  if (IMPORTED_DESIGN_REFERENCES.length === 0) {
    return null;
  }

  const scored = IMPORTED_DESIGN_REFERENCES.map((reference) => {
    let score = 0;
    const id = reference.id.toLowerCase();
    const name = reference.name.toLowerCase();
    const bestFor = reference.bestFor.join(" ").toLowerCase();

    if (haystack.includes(id)) score += 10;
    if (haystack.includes(name)) score += 10;

    for (const tag of reference.bestFor) {
      if (haystack.includes(tag.toLowerCase())) {
        score += 4;
      }
    }

    if (
      (haystack.includes("dashboard") ||
        haystack.includes("admin") ||
        haystack.includes("helpdesk") ||
        haystack.includes("support")) &&
      (id.includes("plain") || bestFor.includes("workbench"))
    ) {
      score += 8;
    }

    if (
      (haystack.includes("landing") ||
        haystack.includes("saas") ||
        haystack.includes("marketing") ||
        haystack.includes("product website")) &&
      (id.includes("linear") || bestFor.includes("polished-saas"))
    ) {
      score += 8;
    }

    if (
      (haystack.includes("developer") ||
        haystack.includes("terminal") ||
        haystack.includes("infrastructure") ||
        haystack.includes("cli")) &&
      (id.includes("warp") || bestFor.includes("developer-tool"))
    ) {
      score += 8;
    }

    if (
      (haystack.includes("fintech") ||
        haystack.includes("finance") ||
        haystack.includes("premium") ||
        haystack.includes("command")) &&
      (id.includes("mercury") || bestFor.includes("fintech"))
    ) {
      score += 8;
    }

    return {
      reference,
      score,
    };
  }).sort((a, b) => b.score - a.score);

  return scored[0]?.reference ?? IMPORTED_DESIGN_REFERENCES[0];
}

export function createImportedDesignReferencePrompt(reference: ImportedDesignReference | null) {
  if (!reference) {
    return "";
  }

  return \`
IMPORTED REFERO DESIGN REFERENCE
Reference: \${reference.name}
Filename: \${reference.filename}
Theme: \${reference.theme}
Best for: \${reference.bestFor.join(", ")}

You must treat the following DESIGN.md reference as the visual source of truth.
Extract its typography, colour, spacing, layout, component, and motion rules.
Do not copy the brand directly.
Do not leak this metadata into visible UI copy.
Use the reference to create original output with the same level of craft.

REFERENCE CONTENT
\${reference.content}

STRICT APPLICATION RULES
- The generated website must visibly reflect this reference.
- Use its colour system, typography rhythm, spacing, card structure, surface hierarchy, and motion guidance.
- Replace generic templates with product-specific sections and realistic UI previews.
- Do not output a plain generic website.
- Do not use unrelated colours, gradients, typography, or card styles.
- Do not display the reference name as visible marketing copy unless the user explicitly asks.
\`.trim();
}
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, output);

console.log(`Generated ${references.length} design reference(s):`);
for (const reference of references) {
  console.log(`- ${reference.id} (${reference.filename})`);
}
console.log(`\nWrote ${path.relative(root, outputFile)}`);
