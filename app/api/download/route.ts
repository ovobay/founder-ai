export async function POST(req: Request) {
  try {
    const { result, files } = await req.json();

    let parsedFiles: FileItem[] = [];

    if (Array.isArray(files)) {
      parsedFiles = files.map((file) => ({
        path: normalizePath(file.path),
        content: String(file.content || ""),
      }));
    } else {
      parsedFiles = parseFiles(result);
    }

    if (parsedFiles.length === 0) {
      return NextResponse.json(
        { error: "No valid project files found." },
        { status: 400 }
      );
    }

    const finalFiles = ensureBaseFiles(parsedFiles);
    const zip = new JSZip();

    for (const file of finalFiles) {
      zip.file(file.path, file.content);
    }

    const blob = await zip.generateAsync({ type: "arraybuffer" });

    return new NextResponse(blob, {
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition":
          'attachment; filename="founder-ai-generated-project.zip"',
      },
    });
  } catch (error) {
    return NextResponse.json({ error: String(error) }, { status: 500 });
  }
}