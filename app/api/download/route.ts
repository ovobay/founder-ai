import JSZip from "jszip";
import { NextResponse } from "next/server";

type FileItem = {
  path: string;
  content: string;
};

function parseFiles(text?: string): FileItem[] {
  if (!text || typeof text !== "string") {
    return [];
  }

  const files: FileItem[] = [];
  const parts = text.split("FILE:");

  for (let part of parts) {
    part = part.trim();
    if (!part) continue;

    const firstLineEnd = part.indexOf("\n");

    if (firstLineEnd === -1) {
      continue;
    }

    const filePath = part.substring(0, firstLineEnd).trim();
    const content = part.substring(firstLineEnd).trim();

    if (!filePath || !content) {
      continue;
    }

    files.push({
      path: normalizePath(filePath),
      content,
    });
  }

  return files;
}

function normalizePath(filePath: string) {
  return filePath
    .replace(/^\/+/, "")
    .replace(/\.\./g, "")
    .replace(/\\/g, "/")
    .trim();
}

function hasFile(files: FileItem[], path: string) {
  return files.some((file) => file.path === path);
}

