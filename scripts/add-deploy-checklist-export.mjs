import fs from "node:fs";
import path from "node:path";

const pagePath = path.join(process.cwd(), "app/page.tsx");
const backupPath = path.join(
  process.cwd(),
  `app/page.backup-before-deploy-checklist-export-${Date.now()}.tsx`
);

if (!fs.existsSync(pagePath)) {
  throw new Error(`Could not find ${pagePath}`);
}

let source = fs.readFileSync(pagePath, "utf8");
fs.writeFileSync(backupPath, source);

function save() {
  fs.writeFileSync(pagePath, source);
}

function die(message) {
  save();
  throw new Error(message);
}

function insertBefore(label, marker, insertion) {
  if (source.includes(insertion.trim())) {
    console.log(`Skipping ${label}: already exists.`);
    return;
  }

  if (!source.includes(marker)) {
    die(`Missing marker: ${label}`);
  }

  source = source.replace(marker, `${insertion}${marker}`);
}

function updateBetween(label, startMarker, endMarker, updater) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start);

  if (start === -1 || end === -1) {
    die(`Could not find section: ${label}`);
  }

  const before = source.slice(0, start);
  const section = source.slice(start, end);
  const after = source.slice(end);

  source = before + updater(section) + after;
}

/**
 * 1. Add markdown export helper.
 */
const deployChecklistHelper = `function createDeployChecklistMarkdown({
  previewState,
  files,
}: {
  previewState: PreviewState;
  files: ChangedFile[];
}) {
  const deployItems = getDeployReadinessItems({
    previewState,
    files,
  });

  const requiredEnvVars = getRequiredEnvironmentVariables({
    projectType: previewState.projectType,
    modules: previewState.modules,
    architecture: previewState.architecture,
    classification: previewState.classification,
  });

  const lines = [
    "# Deployment checklist",
    "",
    \`Generated for: \${previewState.title}\`,
    \`Project type: \${previewState.projectType}\`,
    \`Status: \${previewState.status}\`,
    "",
    "## Build summary",
    "",
    \`- Files: \${files.length}\`,
    \`- Modules: \${previewState.modules.length}\`,
    \`- Database tables: \${previewState.architecture.tables.length}\`,
    \`- API routes: \${previewState.architecture.endpoints.length}\`,
    \`- Security rules: \${previewState.architecture.securityRules.length}\`,
    "",
    "## Classification",
    "",
    \`- Primary category: \${previewState.classification?.primaryCategory ?? "Not classified"}\`,
    \`- Industry: \${previewState.classification?.industry ?? "General"}\`,
    \`- Platform targets: \${previewState.classification?.platformTargets.join(", ") || "web"}\`,
    \`- Complexity: \${previewState.classification?.complexity ?? "standard"}\`,
    "",
    "## Required environment variables",
    "",
    ...(requiredEnvVars.length > 0
      ? requiredEnvVars.flatMap((variable) => [
          \`### \${variable.key}\`,
          "",
          \`- Label: \${variable.label}\`,
          \`- Scope: \${variable.scope}\`,
          \`- Reason: \${variable.reason}\`,
          \`- Example: \\\`\${variable.key}=\${variable.example}\\\`\`,
          "",
        ])
      : ["No required environment variables detected.", ""]),
    "## Deployment tasks",
    "",
    ...deployItems.flatMap((item) => [
      \`### \${item.label}\`,
      "",
      \`Status: \${item.status}\`,
      "",
      item.detail,
      "",
      ...item.checklist.map((check) => \`- [ ] \${check}\`),
      "",
    ]),
    "## Final pre-launch checks",
    "",
    "- [ ] Run production build locally.",
    "- [ ] Check browser console.",
    "- [ ] Check server logs.",
    "- [ ] Test authentication.",
    "- [ ] Test the primary user workflow.",
    "- [ ] Confirm secrets are not committed.",
    "- [ ] Confirm production environment variables are configured.",
    "- [ ] Confirm database migrations have run.",
    "- [ ] Confirm RLS/security rules are reviewed.",
    "",
    "> Generated by Founder AI. Review before launch, because the internet is not a forgiving place.",
    "",
  ];

  return lines.join("\\n");
}

`;

if (!source.includes("function createDeployChecklistMarkdown(")) {
  if (source.includes("function DeployReadinessPanel(")) {
    insertBefore(
      "createDeployChecklistMarkdown helper",
      "function DeployReadinessPanel(",
      deployChecklistHelper
    );
  } else if (source.includes("function PublishReadinessWorkspace(")) {
    insertBefore(
      "createDeployChecklistMarkdown helper",
      "function PublishReadinessWorkspace(",
      deployChecklistHelper
    );
  } else {
    insertBefore(
      "createDeployChecklistMarkdown helper",
      "function PublishReadinessCard(",
      deployChecklistHelper
    );
  }

  console.log("Added createDeployChecklistMarkdown helper.");
} else {
  console.log("createDeployChecklistMarkdown helper already exists.");
}

/**
 * 2. Pass onCreateFile and onSaveFile into DeployReadinessPanel.
 */
updateBetween(
  "PublishReadinessWorkspace",
  "function PublishReadinessWorkspace({",
  "function PublishReadinessCard(",
  (section) => {
    let updated = section;

    if (
      updated.includes("<DeployReadinessPanel") &&
      !updated.includes("onCreateFile={onCreateFile}") &&
      !updated.includes("onSaveFile={onSaveFile}")
    ) {
      updated = updated.replace(
        `<DeployReadinessPanel
          previewState={previewState}
          files={files}
        />`,
        `<DeployReadinessPanel
          previewState={previewState}
          files={files}
          onCreateFile={onCreateFile}
          onSaveFile={onSaveFile}
          setWorkspaceError={setWorkspaceError}
        />`
      );

      console.log("Passed file handlers into DeployReadinessPanel.");
    } else {
      console.log("DeployReadinessPanel already has file handlers or marker differs.");
    }

    return updated;
  }
);

/**
 * 3. Update DeployReadinessPanel props and add export action.
 */
updateBetween(
  "DeployReadinessPanel",
  "function DeployReadinessPanel({",
  "function DeployReadinessCard(",
  (section) => {
    let updated = section;

    if (!updated.includes("onCreateFile,")) {
      updated = updated.replace(
        `function DeployReadinessPanel({
  previewState,
  files,
}: {
  previewState: PreviewState;
  files: ChangedFile[];
}) {`,
        `function DeployReadinessPanel({
  previewState,
  files,
  onCreateFile,
  onSaveFile,
  setWorkspaceError,
}: {
  previewState: PreviewState;
  files: ChangedFile[];
  onCreateFile: (
    path: string,
    contents?: string
  ) => Promise<DatabaseProjectFile | undefined>;
  onSaveFile: (
    fileId: string,
    filePath: string,
    contents: string
  ) => Promise<DatabaseProjectFile>;
  setWorkspaceError: (value: string) => void;
}) {`
      );

      console.log("Updated DeployReadinessPanel props.");
    } else {
      console.log("DeployReadinessPanel props already include file handlers.");
    }

    if (!updated.includes("const [isExportingDeployChecklist")) {
      updated = updated.replace(
        `  const deployItems = getDeployReadinessItems({
    previewState,
    files,
  });`,
        `  const deployItems = getDeployReadinessItems({
    previewState,
    files,
  });

  const [isExportingDeployChecklist, setIsExportingDeployChecklist] =
    useState(false);
  const [deployExportMessage, setDeployExportMessage] = useState("");

  async function handleExportDeployChecklist() {
    setIsExportingDeployChecklist(true);
    setDeployExportMessage("");
    setWorkspaceError("");

    const filePath = "config/deploy-checklist.md";
    const contents = createDeployChecklistMarkdown({
      previewState,
      files,
    });
    const existingFile = files.find((file) => file.path === filePath);

    try {
      if (existingFile) {
        await onSaveFile(existingFile.id, filePath, contents);
        setDeployExportMessage("config/deploy-checklist.md updated.");
      } else {
        await onCreateFile(filePath, contents);
        setDeployExportMessage("config/deploy-checklist.md exported.");
      }
    } catch (error) {
      const message =
        error instanceof Error
          ? error.message
          : "Failed to export deployment checklist.";

      setDeployExportMessage(message);
      setWorkspaceError(message);
    } finally {
      setIsExportingDeployChecklist(false);
    }
  }`
      );

      console.log("Added deploy checklist export state and handler.");
    } else {
      console.log("Deploy checklist export handler already exists.");
    }

    if (!updated.includes("Export deployment checklist")) {
      updated = updated.replace(
        `          <p
            style={{
              margin: 0,
              color: "#4b5563",
              fontSize: "13px",
              lineHeight: 1.55,
            }}
          >
            {ready.length} ready, {needsSetup.length} need setup, and{" "}
            {blocked.length} blocked. A tidy little autopsy before Vercel gets involved.
          </p>
        </div>

        <span`,
        `          <p
            style={{
              margin: 0,
              color: "#4b5563",
              fontSize: "13px",
              lineHeight: 1.55,
            }}
          >
            {ready.length} ready, {needsSetup.length} need setup, and{" "}
            {blocked.length} blocked. A tidy little autopsy before Vercel gets involved.
          </p>

          <div
            style={{
              marginTop: "12px",
              display: "flex",
              alignItems: "center",
              gap: "10px",
              flexWrap: "wrap",
            }}
          >
            <button
              type="button"
              className="pill-button"
              onClick={handleExportDeployChecklist}
              disabled={isExportingDeployChecklist}
            >
              {isExportingDeployChecklist
                ? "Exporting..."
                : "Export deployment checklist"}
            </button>

            <span
              style={{
                color:
                  deployExportMessage.toLowerCase().includes("failed") ||
                  deployExportMessage.toLowerCase().includes("already")
                    ? "#991b1b"
                    : "#4b5563",
                fontSize: "12px",
                fontWeight: 700,
              }}
            >
              {deployExportMessage ||
                "Export launch steps into the project file tree."}
            </span>
          </div>
        </div>

        <span`
      );

      console.log("Added export deployment checklist UI.");
    } else {
      console.log("Export deployment checklist UI already exists.");
    }

    return updated;
  }
);

save();

